#!/usr/bin/env python3
"""The WebVTT track, generated from the same shot list the film is cut from.

The chapter cards carry the narrative, and a browser that autoplays this
muted -- which is the only kind of autoplay anyone should ship -- gives a
viewer no audio to fall back on. So every shot that says something carries a
caption in shots.json, and a shot without one extends the previous cue until
the next shot that has one. That is how the twelve-shot montage ends up under
a single line rather than twelve flickering ones.
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SPEC = json.load(open(os.path.join(ROOT, "film", "shots.json")))
SEC_PER_BEAT = 60.0 / SPEC["tempo_bpm"]


def stamp(sec: float) -> str:
    h, rem = divmod(sec, 3600)
    m, s = divmod(rem, 60)
    return f"{int(h):02d}:{int(m):02d}:{s:06.3f}"


def main(out_path):
    shots = sorted(SPEC["shots"], key=lambda s: s["beat"])
    end = sum(s["beats"] for s in shots)
    cues = []
    for s in shots:
        if s.get("caption"):
            cues.append([s["beat"], None, s["caption"]])
    for i, c in enumerate(cues):
        c[1] = cues[i + 1][0] if i + 1 < len(cues) else end

    lines = ["WEBVTT", "", "NOTE", "Generated by film/tools/captions.py from film/shots.json.", ""]
    for i, (a, b, text) in enumerate(cues, 1):
        lines.append(str(i))
        lines.append(f"{stamp(a * SEC_PER_BEAT)} --> {stamp(b * SEC_PER_BEAT)}")
        lines.append(text)
        lines.append("")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    print(f"{len(cues)} cues -> {out_path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1
         else os.path.join(ROOT, "site", "public", "film", "film.vtt"))
