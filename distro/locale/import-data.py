#!/usr/bin/env python3
# Make the data catalogues the installer shows next to its own text:
#
#   <lang>/countries.msg   country names, msgid = the ISO 3166-1 alpha-2 code
#                          ("FR"), msgstr = the name in <lang> ("Francia"),
#                          from iso-codes' iso_3166-1 domain
#   <lang>/keyboards.msg   keyboard layout and variant descriptions, msgid =
#                          the English description in xkeyboard-config's
#                          rules/base.lst, msgstr = xkeyboard-config's own
#                          translation of it
#
# Both are the build host's (Arch: iso-codes, xkeyboard-config), read from
# their gettext .mo files, and written in kit's .msg format so the same
# library reads them. Only entries with a translation are written; the
# installer falls back to tzdata's and base.lst's English for the rest.
# Run it again when either package changes; the output is committed, like
# every other catalogue, so a build never depends on what the host has.
#
#	python3 -I distro/locale/import-data.py
#
# Licences: iso-codes' translations are LGPL-2.1, xkeyboard-config's are
# under its MIT-style licence (its COPYING). Each file's header says which.
import gettext
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LOCALE = '/usr/share/locale'
ISO_JSON = '/usr/share/iso-codes/json/iso_3166-1.json'
BASE_LST = '/usr/share/X11/xkb/rules/base.lst'

# language dir -> (.mo language, header values copied from installer.msg)
LANGS = ['fr', 'de', 'es', 'ar', 'ja']


def header(lang):
    # language, name, english, plural and direction from the installer's
    # catalogue, so every file of a language says the same thing.
    keys = {}
    with open(os.path.join(HERE, lang, 'installer.msg'), encoding='utf-8') as f:
        for line in f:
            if line.startswith('msgid'):
                break
            if '=' in line and not line.startswith('#'):
                k, v = line.split('=', 1)
                keys[k.strip()] = v.strip()
    out = []
    for k in ('language', 'name', 'english', 'plural', 'direction'):
        if k in keys:
            out.append('%-9s = %s' % (k, keys[k]))
    return '\n'.join(out) + '\n'


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def mo(domain, lang):
    path = os.path.join(LOCALE, lang, 'LC_MESSAGES', domain + '.mo')
    with open(path, 'rb') as f:
        return gettext.GNUTranslations(f)


def descriptions():
    out, section = [], ''
    with open(BASE_LST, encoding='utf-8') as f:
        for raw in f:
            line = raw.rstrip()
            if line.startswith('!'):
                section = line[1:].strip()
                continue
            s = line.strip()
            if not s or s.startswith('#'):
                continue
            parts = s.split(None, 1)
            if len(parts) < 2:
                continue
            rest = parts[1]
            if section == 'layout':
                out.append(rest.strip())
            elif section == 'variant' and ':' in rest:
                out.append(rest.split(':', 1)[1].strip())
    seen, uniq = set(), []
    for d in out:
        if d not in seen:
            seen.add(d)
            uniq.append(d)
    return uniq


def main():
    countries = json.load(open(ISO_JSON, encoding='utf-8'))['3166-1']
    descs = descriptions()
    for lang in LANGS:
        iso = mo('iso_3166-1', lang)
        xkb = mo('xkeyboard-config', lang)

        lines = ['# Country names in this language, for the installer\'s time zone list.',
                 '# Generated by distro/locale/import-data.py from iso-codes\' iso_3166-1',
                 '# translations (LGPL-2.1); msgid is the ISO 3166-1 alpha-2 code.',
                 '# Do not edit: fix the translation upstream, or the script.']
        n = 0
        body = []
        for c in sorted(countries, key=lambda c: c['alpha_2']):
            t = iso.gettext(c['name'])
            if t == c['name'] and 'common_name' in c:
                t2 = iso.gettext(c['common_name'])
                if t2 != c['common_name']:
                    t = t2
            if t == c['name'] and lang not in ('en',):
                # untranslated; the installer keeps tzdata's English
                continue
            body.append('msgid %s\nmsgstr %s\n' % (q(c['alpha_2']), q(t)))
            n += 1
        with open(os.path.join(HERE, lang, 'countries.msg'), 'w', encoding='utf-8') as f:
            f.write('\n'.join(lines) + '\n' + header(lang) + '\n' + '\n'.join(body))
        m = 0
        body = []
        for d in descs:
            t = xkb.gettext(d)
            if t == d or '%' in d or '%' in t:
                continue
            body.append('msgid %s\nmsgstr %s\n' % (q(d), q(t)))
            m += 1
        lines = ['# Keyboard layout descriptions in this language, for the installer.',
                 '# Generated by distro/locale/import-data.py from xkeyboard-config\'s own',
                 '# translations (its MIT-style licence, COPYING); msgid is the English',
                 '# description in rules/base.lst. Do not edit: fix it upstream.']
        with open(os.path.join(HERE, lang, 'keyboards.msg'), 'w', encoding='utf-8') as f:
            f.write('\n'.join(lines) + '\n' + header(lang) + '\n' + '\n'.join(body))
        print('%s: %d countries, %d of %d keyboard descriptions' % (lang, n, m, len(descs)))


if __name__ == '__main__':
    sys.exit(main())
