# --- fonts and fonts-emoji: distro/apps/fonts.list ---------------------------
fonts_recipe() { # fonts_recipe <pkg> <set> <desc> <icon> <details>
	header " from distro/apps/fonts.list (set $2)"
	cat <<EOF
#
# palmy finds fonts by walking /usr/share/fonts (no fontconfig, no cache), so
# installing the files is all it takes. Licenses go to
# /usr/share/licenses/fonts beside them.
pkgname  = $1
pkgver   = $OWN_VER
pkgrel   = 0
pkgdesc  = $3
license  = OFL-1.1 AND Bitstream-Vera
category = System
icon     = $4
details  = $5

EOF
	grep -v '^#' "$DISTRO/apps/fonts.list" | while read -r src dst set; do
		if [ -z "${src:-}" ] || [ "$set" != "$2" ]; then continue; fi
		case "$src" in /*) ;; *) src="\${PALMFRAME_ROOT}/$src" ;; esac
		echo "file     = $src -> $dst mode 0644"
	done
}
