#!/usr/bin/env bash
# Write the PALMBUILD recipes whose contents come from somewhere else.
#
#	distro/recipes/generate.sh
#
# A PALMBUILD is a declaration with no loops and no shell (distro/palm/
# PALMBUILD.md), which is right for a package of three files and wrong for
# one whose file list lives elsewhere: busybox's applets are whatever
# `busybox --list` says, glibc's version is whatever the build host runs,
# palmframe-base is distro/base/root plus distro/base/layout, the fonts are
# distro/apps/fonts.list, and the applications are distro/apps/default.list.
# Copying those lists into hand-written recipes would let them drift, so this
# script writes them, and `make -C distro` runs it before every build. The
# output is committed anyway, so a reader sees exactly what each package
# holds without running anything.
#
# Hand-written recipes (linux, palm-init, palm, palm-login, doas, passwd, palmd, greeter,
# palmy-wm, palmframe-demo, and the installer's palm-install, installer and
# palmframe-live) are left alone.
#
# Every recipe also carries the fields Software (apps/store) reads:
# `category` (its shelf in Discover; one of the closed list in
# distro/palm/PALMBUILD.md), `icon` (a lucide icon name the store draws) and
# `details` (the prose on the package's page). pkgdesc is the one-line
# summary under the name.
#
# Sources in the recipes are spelled ${PALMFRAME_ROOT} (the checkout),
# ${PALMFRAME_OUT} (distro/out) and ${PALMFRAME_KEYS} (distro/build/keys);
# distro/Makefile exports all three before calling `palm build`. Host files
# (glibc, libxkbcommon, the XKB data, some fonts) are absolute paths.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
DISTRO="$(dirname "$HERE")"
ROOT="$(dirname "$DISTRO")"
BUSYBOX="${BUSYBOX:-$DISTRO/out/busybox}"

# Our own packages share one version until there is a reason to split them.
OWN_VER=0.1.0

# A version as the host's package manager reports it, reduced to what palm
# accepts as a pkgver (digits and dots: Arch's "2.44+r24+g16be..." -> 2.44).
host_version() {
	local v
	v="$(pacman -Q "$1" 2>/dev/null | awk '{print $2}')" || true
	v="${v%%-*}"
	v="${v%%+*}"
	v="${v#*:}"
	[[ "$v" =~ ^[0-9]+(\.[0-9]+)*$ ]] || v="$2"
	echo "$v"
}

header() {
	cat <<EOF
# Generated by distro/recipes/generate.sh$1 -- do not edit;
# change the source and run \`make -C distro recipes\`.
EOF
}

emit() { # emit <pkg>: stdin -> distro/recipes/<pkg>/PALMBUILD, only if changed
	mkdir -p "$HERE/$1"
	local tmp
	tmp="$(mktemp)"
	cat >"$tmp"
	if cmp -s "$tmp" "$HERE/$1/PALMBUILD"; then
		rm -f "$tmp"
	else
		mv "$tmp" "$HERE/$1/PALMBUILD"
		chmod 0644 "$HERE/$1/PALMBUILD"
		echo "recipes: wrote $1"
	fi
}

# Owners in distro/base/layout are numeric (they must mean something before
# /etc/passwd exists); the package records the CONTRACT's names as well, so
# the installed database reads palm:palm rather than 1000:1000.
owner_name() {
	local u="${1%%:*}" g="${1#*:}"
	echo "$(id_name "$u"):$(id_name "$g")"
}
id_name() {
	case "$1" in
	0) echo root ;; 5) echo tty ;; 10) echo wheel ;; 39) echo video ;;
	63) echo audio ;; 97) echo input ;; 900) echo greeter ;; 1000) echo palm ;;
	*) echo "$1" ;;
	esac
}

# --- palmframe-base: distro/base/root and distro/base/layout -----------------
{
	header " from distro/base/root and distro/base/layout"
	cat <<EOF
#
# The filesystem itself: merged /usr, /etc (users, services, repositories),
# the mount points palm-init mounts on, and /etc/skel. Every other
# package depends on this one, so it is always installed first and its
# /etc/passwd is in place when later packages' owners are resolved.
pkgname  = palmframe-base
pkgver   = $OWN_VER
pkgrel   = 0
pkgdesc  = The Palmframe filesystem layout, users and base configuration
license  = MIT
category = System
icon     = hard-drive
details  = The skeleton every other package stands on: merged /usr, /etc with the users, groups and services, the repository list and its signing key, and the mount points palm-init mounts on.
install_user = root
install_user = palm
install_user = greeter

EOF
	# The trees first: `dir` lines from the layout come after them, so a
	# directory's mode and owner are the layout's, not the tree's 0755.
	for top in "$DISTRO"/base/root/*; do
		t="$(basename "$top")"
		echo "tree     = \${PALMFRAME_ROOT}/distro/base/root/$t -> /$t"
	done
	echo "file     = \${PALMFRAME_KEYS}/palmframe.pub -> /etc/palm/keys/palmframe.pub mode 0644"
	echo
	while read -r kind path a b; do
		case "$kind" in
		'' | '#'*) continue ;;
		dir)
			echo "dir      = /$path mode $a"
			if [ -n "${b:-}" ]; then echo "owner    = /$path $(owner_name "$b")"; fi
			;;
		symlink) echo "symlink  = /$path -> $a" ;;
		mode) echo "mode     = /$path $a" ;;
		owner) echo "owner    = /$path $(owner_name "$a")" ;;
		*) echo "generate: unknown layout line: $kind $path" >&2; exit 1 ;;
		esac
	done <"$DISTRO/base/layout"
} | emit palmframe-base

# --- busybox: the binary and one symlink per applet --------------------------
# Applets that would shadow a Palmframe program are left out; today that is
# busybox's PPP `chat`, which collides with the chat application's name, and
# passwd, which distro/passwd replaces (busybox is not setuid, so its passwd
# works only for root).
BB_SKIP=" init linuxrc chat passwd modprobe insmod depmod modinfo "
BB_VER="$( (set +o pipefail; "$BUSYBOX" 2>/dev/null | head -1 | sed -n "s/^BusyBox v\([0-9.]*\).*/\1/p") )"
{
	header " from \`busybox --list\`"
	cat <<EOF
#
# The userland: sh, coreutils, mount, getty/login, udhcpc, syslogd, vi.
# Statically linked, so it needs nothing else. Built by distro/busybox/build.sh
# without an init applet (palm-init is PID 1).
pkgname  = busybox
pkgver   = ${BB_VER:-1.37.0}
pkgrel   = 0
pkgdesc  = Tiny versions of many common UNIX utilities in a single static binary
license  = GPL-2.0-only
url      = https://busybox.net
category = System
icon     = terminal
details  = The shell and the command-line userland in one statically linked program: sh, the coreutils, mount, getty and login, udhcpc, syslogd and vi, each a link to the same binary.
depend   = palmframe-base
provides = cmd:sh

file     = \${PALMFRAME_OUT}/busybox -> /usr/bin/busybox mode 0755
EOF
	for applet in $("$BUSYBOX" --list | sort); do
		case "$BB_SKIP" in *" $applet "*) continue ;; esac
		echo "symlink  = /usr/bin/$applet -> busybox"
	done
} | emit busybox

