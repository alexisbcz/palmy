#!/usr/bin/env bash
# Write the PALMBUILD recipes whose contents come from somewhere else.
#
#	distro/recipes/generate.sh
#
# A PALMBUILD is a declaration with no loops and no shell (distro/palm/
# PALMBUILD.md), which is right for a package of three files and wrong for
# one whose file list lives elsewhere: busybox's applets are whatever
# `busybox --list` says, glibc's version is whatever the build host runs,
# palmframe-base is distro/base/root plus distro/base/layout, the fonts are
# distro/apps/fonts.list, and the applications are distro/apps/default.list.
# Copying those lists into hand-written recipes would let them drift, so this
# script writes them, and `make -C distro` runs it before every build. The
# output is committed anyway, so a reader sees exactly what each package
# holds without running anything.
#
# Hand-written recipes (linux, palm-init, palm, palm-login, greeter and
# palmy-wm) are left alone.
#
# Sources in the recipes are spelled ${PALMFRAME_ROOT} (the checkout),
# ${PALMFRAME_OUT} (distro/out) and ${PALMFRAME_KEYS} (distro/build/keys);
# distro/Makefile exports all three before calling `palm build`. Host files
# (glibc, libxkbcommon, the XKB data, some fonts) are absolute paths.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
DISTRO="$(dirname "$HERE")"
ROOT="$(dirname "$DISTRO")"
BUSYBOX="${BUSYBOX:-$DISTRO/out/busybox}"

# Our own packages share one version until there is a reason to split them.
OWN_VER=0.1.0

# A version as the host's package manager reports it, reduced to what palm
# accepts as a pkgver (digits and dots: Arch's "2.44+r24+g16be..." -> 2.44).
host_version() {
	local v
	v="$(pacman -Q "$1" 2>/dev/null | awk '{print $2}')" || true
	v="${v%%-*}"
	v="${v%%+*}"
	v="${v#*:}"
	[[ "$v" =~ ^[0-9]+(\.[0-9]+)*$ ]] || v="$2"
	echo "$v"
}

header() {
	cat <<EOF
# Generated by distro/recipes/generate.sh$1 -- do not edit;
# change the source and run \`make -C distro recipes\`.
EOF
}

emit() { # emit <pkg>: stdin -> distro/recipes/<pkg>/PALMBUILD, only if changed
	mkdir -p "$HERE/$1"
	local tmp
	tmp="$(mktemp)"
	cat >"$tmp"
	if cmp -s "$tmp" "$HERE/$1/PALMBUILD"; then
		rm -f "$tmp"
	else
		mv "$tmp" "$HERE/$1/PALMBUILD"
		chmod 0644 "$HERE/$1/PALMBUILD"
		echo "recipes: wrote $1"
	fi
}

# Owners in distro/base/layout are numeric (they must mean something before
# /etc/passwd exists); the package records the CONTRACT's names as well, so
# the installed database reads palm:palm rather than 1000:1000.
owner_name() {
	local u="${1%%:*}" g="${1#*:}"
	echo "$(id_name "$u"):$(id_name "$g")"
}
id_name() {
	case "$1" in
	0) echo root ;; 5) echo tty ;; 10) echo wheel ;; 39) echo video ;;
	63) echo audio ;; 97) echo input ;; 900) echo greeter ;; 1000) echo palm ;;
	*) echo "$1" ;;
	esac
}

# --- palmframe-base: distro/base/root and distro/base/layout -----------------
{
	header " from distro/base/root and distro/base/layout"
	cat <<EOF
#
# The filesystem itself: merged /usr, /etc (users, services, repositories),
# the mount points palm-init mounts on, and palm's own home. Every other
# package depends on this one, so it is always installed first and its
# /etc/passwd is in place when later packages' owners are resolved.
pkgname  = palmframe-base
pkgver   = $OWN_VER
pkgrel   = 0
pkgdesc  = The Palmframe filesystem layout, users and base configuration
license  = MIT
install_user = root
install_user = palm
install_user = greeter

EOF
	# The trees first: `dir` lines from the layout come after them, so a
	# directory's mode and owner are the layout's, not the tree's 0755.
	for top in "$DISTRO"/base/root/*; do
		t="$(basename "$top")"
		echo "tree     = \${PALMFRAME_ROOT}/distro/base/root/$t -> /$t"
	done
	echo "file     = \${PALMFRAME_KEYS}/palmframe.pub -> /etc/palm/keys/palmframe.pub mode 0644"
	echo
	while read -r kind path a b; do
		case "$kind" in
		'' | '#'*) continue ;;
		dir)
			echo "dir      = /$path mode $a"
			if [ -n "${b:-}" ]; then echo "owner    = /$path $(owner_name "$b")"; fi
			;;
		symlink) echo "symlink  = /$path -> $a" ;;
		mode) echo "mode     = /$path $a" ;;
		owner) echo "owner    = /$path $(owner_name "$a")" ;;
		*) echo "generate: unknown layout line: $kind $path" >&2; exit 1 ;;
		esac
	done <"$DISTRO/base/layout"
} | emit palmframe-base

# --- busybox: the binary and one symlink per applet --------------------------
# Applets that would shadow a Palmframe program are left out; today that is
# busybox's PPP `chat`, which collides with the chat application's name.
BB_SKIP=" init linuxrc chat "
BB_VER="$( (set +o pipefail; "$BUSYBOX" 2>/dev/null | head -1 | sed -n "s/^BusyBox v\([0-9.]*\).*/\1/p") )"
{
	header " from \`busybox --list\`"
	cat <<EOF
#
# The userland: sh, coreutils, mount, getty/login, udhcpc, syslogd, vi.
# Statically linked, so it needs nothing else. Built by distro/busybox/build.sh
# without an init applet (palm-init is PID 1).
pkgname  = busybox
pkgver   = ${BB_VER:-1.37.0}
pkgrel   = 0
pkgdesc  = Tiny versions of many common UNIX utilities in a single static binary
license  = GPL-2.0-only
url      = https://busybox.net
depend   = palmframe-base
provides = cmd:sh

file     = \${PALMFRAME_OUT}/busybox -> /usr/bin/busybox mode 0755
EOF
	for applet in $("$BUSYBOX" --list | sort); do
		case "$BB_SKIP" in *" $applet "*) continue ;; esac
		echo "symlink  = /usr/bin/$applet -> busybox"
	done
} | emit busybox

# --- glibc: the runtime pieces every palmy binary links ----------------------
# `ldd` of every shipped dynamic binary names exactly these three (checked by
# distro/Makefile's `check-libs`); everything else in glibc stays on the host.
GLIBC_VER="$(host_version glibc 2.44)"
{
	header " from the build host's glibc"
	cat <<EOF
#
# Taken from the build host rather than built: every Odin binary links the
# host's glibc, so shipping the same files is what makes them run unchanged.
# The loader lives in /usr/lib; /lib64 -> usr/lib (palmframe-base) is how the
# ELF interpreter path /lib64/ld-linux-x86-64.so.2 finds it.
pkgname  = glibc
pkgver   = $GLIBC_VER
pkgrel   = 0
pkgdesc  = GNU C Library runtime (from the build host)
license  = LGPL-2.1-or-later
url      = https://www.gnu.org/software/libc
depend   = palmframe-base
provides = so:libc.so.6 so:libm.so.6 so:ld-linux-x86-64.so.2

file     = /usr/lib/libc.so.6 -> /usr/lib/libc.so.6 mode 0755
file     = /usr/lib/libm.so.6 -> /usr/lib/libm.so.6 mode 0755
file     = /usr/lib64/ld-linux-x86-64.so.2 -> /usr/lib/ld-linux-x86-64.so.2 mode 0755
EOF
} | emit glibc

# --- libxkbcommon -------------------------------------------------------------
XKB_SO="$(readlink -f /usr/lib/libxkbcommon.so.0)"
{
	header " from the build host's libxkbcommon"
	cat <<EOF
#
# palmy clients dlopen libxkbcommon to compile the keymap the window manager
# sends them; without it they fall back to a built-in US layout.
pkgname  = libxkbcommon
pkgver   = $(host_version libxkbcommon 1.0)
pkgrel   = 0
pkgdesc  = Keymap handling library (from the build host)
license  = MIT
url      = https://xkbcommon.org
depend   = glibc
provides = so:libxkbcommon.so.0

file     = $XKB_SO -> /usr/lib/$(basename "$XKB_SO") mode 0755
symlink  = /usr/lib/libxkbcommon.so.0 -> $(basename "$XKB_SO")
EOF
} | emit libxkbcommon

# --- xkeyboard-config ---------------------------------------------------------
{
	header " from the build host's xkeyboard-config"
	cat <<EOF
#
# The XKB rules, keycodes and layouts the window manager's own keymap compiler
# reads (rules evdev, layout from its config). Without them it uses its
# built-in US keymap.
pkgname  = xkeyboard-config
pkgver   = $(host_version xkeyboard-config 2.0)
pkgrel   = 0
pkgdesc  = X keyboard configuration data (from the build host)
license  = MIT
url      = https://www.freedesktop.org/wiki/Software/XKeyboardConfig

tree     = /usr/share/X11/xkb -> /usr/share/X11/xkb
EOF
} | emit xkeyboard-config

# --- fonts and fonts-emoji: distro/apps/fonts.list ---------------------------
fonts_recipe() { # fonts_recipe <pkg> <set> <desc>
	header " from distro/apps/fonts.list (set $2)"
	cat <<EOF
#
# palmy finds fonts by walking /usr/share/fonts (no fontconfig, no cache), so
# installing the files is all it takes. Licenses go to
# /usr/share/licenses/fonts beside them.
pkgname  = $1
pkgver   = $OWN_VER
pkgrel   = 0
pkgdesc  = $3
license  = OFL-1.1 AND Bitstream-Vera

EOF
	grep -v '^#' "$DISTRO/apps/fonts.list" | while read -r src dst set; do
		if [ -z "${src:-}" ] || [ "$set" != "$2" ]; then continue; fi
		case "$src" in /*) ;; *) src="\${PALMFRAME_ROOT}/$src" ;; esac
		echo "file     = $src -> $dst mode 0644"
	done
}
fonts_recipe fonts base "Geist, JetBrains Mono and DejaVu Sans: the fonts every palmy application uses" | emit fonts
fonts_recipe fonts-emoji emoji "Noto Color Emoji" | emit fonts-emoji

# --- the applications ---------------------------------------------------------
# One package per program: the default set (distro/apps/default.list, minus
# wm and greeter, which have hand-written recipes as the session) plus a few
# that work on the bare system but are not installed by default -- they are
# what `palm add` on a fresh machine has to choose from.
EXTRA_APPS="shop track pickdemo emoji prose"
declare -A DESC=(
	[term]="The palmy terminal" [launcher]="Application launcher"
	[files]="File manager" [editor]="Text editor" [notes]="Markdown notes"
	[calc]="Calculator" [sysmon]="System monitor" [image]="Image viewer"
	[docs]="Documents" [sheets]="Spreadsheets" [slides]="Presentations"
	[calendar]="Calendar" [reader]="PDF and e-book reader"
	[photoshop]="Image editor" [maps]="Maps" [money]="Personal finance"
	[torrent]="BitTorrent client" [shop]="Shop demo" [track]="Time tracker"
	[pickdemo]="Date and colour picker demo" [emoji]="Emoji picker"
	[prose]="The prose engine behind docs (command line)"
)
apps="$(grep -v '^#' "$DISTRO/apps/default.list" | grep -vx -e wm -e greeter -e '') $EXTRA_APPS"
for app in $apps; do
	deps="glibc fonts libxkbcommon"
	case "$app" in
	prose) deps="glibc" ;;
	term) deps="$deps busybox" ;; # the shell it runs
	docs) deps="$deps prose" ;;   # runs prose as a subprocess
	esac
	{
		header " for distro/apps/default.list and EXTRA_APPS"
		cat <<EOF
#
# Built by distro/apps/build.sh into distro/out/bin/$app.
pkgname  = $app
pkgver   = $OWN_VER
pkgrel   = 0
pkgdesc  = ${DESC[$app]:-$app}
license  = MIT
depend   = $deps
provides = cmd:$app

file     = \${PALMFRAME_OUT}/bin/$app -> /usr/bin/$app mode 0755
EOF
		if [ -f "$DISTRO/apps/desktop/$app.desktop" ]; then
			echo "file     = \${PALMFRAME_ROOT}/distro/apps/desktop/$app.desktop -> /usr/share/applications/$app.desktop mode 0644"
		fi
	} | emit "$app"
done

# --- palmframe: the meta-package ---------------------------------------------
{
	header " from distro/apps/default.list"
	cat <<EOF
#
# Everything a Palmframe machine has after installation: \`palm add palmframe\`
# into an empty root is how distro/image/build.sh makes the disk image.
pkgname  = palmframe
pkgver   = $OWN_VER
pkgrel   = 0
pkgdesc  = The Palmframe system: kernel, init, login, window manager and the default applications
license  = MIT
depend   = palmframe-base linux busybox glibc palm-init palm palm-login
depend   = palmy-wm greeter fonts libxkbcommon xkeyboard-config
depend   = $(grep -v '^#' "$DISTRO/apps/default.list" | grep -vx -e wm -e greeter -e '' | tr '\n' ' ' | sed 's/ $//')
EOF
} | emit palmframe
