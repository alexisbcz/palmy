#!/usr/bin/env bash
# Render every registered case and diff it against the browser capture.
#
# Every path is derived from where this script actually is, so running it from
# a git worktree measures *that* worktree. It used to `cd` to a hardcoded
# /home/alex/Work/palmy, which meant a worktree agent ran the documented
# command, watched it build and report 182 cases at mean mae 2.953, and had
# measured the main checkout rather than their own changes.
#
# Environment, all optional:
#   PARITY_ROOT   the parity/ directory to measure (default: this script's)
#   PARITY_WEB    the browser captures to measure against (see below)
#   ODIN          the compiler to build with
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${PARITY_ROOT:-$(dirname "$HERE")}"
REPO="$(dirname "$ROOT")"
cd "$ROOT" || exit 1

ODIN=${ODIN:-/home/alex/.local/share/mise/installs/odin/dev-2026-09/odin}

# The browser captures. `.gitignore` excludes out/web/*.png -- they are
# regenerated by harness/capture.mjs, not committed -- so a fresh worktree has
# all 182 geometry JSONs and none of the images, and diffing against them
# would compare nothing at all. Borrow the main checkout's captures in that
# case, and say so: they are browser output and do not depend on which tree
# the Odin side is built from.
have_png() { compgen -G "$1/*.png" > /dev/null 2>&1; }

WEB="${PARITY_WEB:-$ROOT/out/web}"
if ! have_png "$WEB"; then
  COMMON="$(git -C "$ROOT" rev-parse --path-format=absolute --git-common-dir 2>/dev/null)"
  if [ -n "${COMMON:-}" ] && have_png "$(dirname "$COMMON")/parity/out/web"; then
    WEB="$(dirname "$COMMON")/parity/out/web"
    echo "note: no browser captures under $ROOT/out/web (they are gitignored)"
    echo "      measuring against $WEB"
  fi
fi
if ! have_png "$WEB"; then
  echo "error: no browser captures in $WEB -- run parity/harness/capture.mjs first" >&2
  exit 1
fi

echo "measuring $REPO"
export PARITY_ROOT="$ROOT" PARITY_WEB="$WEB"

[ -x odin/pixdiff.bin ] || "$ODIN" build odin/pixdiff -collection:palmy="$REPO/palmy" -collection:shadcn="$REPO/shadcn" -o:speed -out:odin/pixdiff.bin || exit 1
"$ODIN" build odin/render -collection:palmy="$REPO/palmy" -collection:shadcn="$REPO/shadcn" -o:speed -out:odin/render.bin || exit 1
./odin/render.bin --all 2>/dev/null | tail -1

mkdir -p out/diff
: > out/diff/metrics.ndjson
for ref in "$WEB"/*.png; do
  id=$(basename "$ref" .png)
  cand="out/odin/$id.png"
  if [ ! -f "$cand" ]; then
    printf '{"id":"%s","status":"not-implemented"}\n' "$id" >> out/diff/metrics.ndjson
    continue
  fi
  m=$(./odin/pixdiff.bin "$ref" "$cand" --out "out/diff/$id.png" --json 2>/dev/null)
  if [ -n "$m" ]; then
    printf '{"id":"%s","status":"ok","metrics":%s}\n' "$id" "$m" >> out/diff/metrics.ndjson
  else
    printf '{"id":"%s","status":"diff-failed"}\n' "$id" >> out/diff/metrics.ndjson
  fi
done
node tools/report.mjs
