#!/usr/bin/env python3
"""Generate palmy/keysym_table.odin from X11's <X11/keysymdef.h>.

A keysym in the legacy range 0x0100-0x20ff (Latin-2..4, Katakana, Arabic,
Cyrillic, Greek, technical and publishing symbols, Hebrew, Thai, Hangul,
Armenian, Georgian, the euro sign...) does not carry its character in its
value the way Latin-1 and the 0x01000000-prefixed Unicode keysyms do. The
mapping is a table, and keysymdef.h states it in a comment on every keysym
that has one:

    #define XK_Cyrillic_a  0x06c1  /* U+0430 CYRILLIC SMALL LETTER A */
    #define XK_topleftradical 0x08a2  /*(U+250C BOX DRAWINGS ...)*/

Both forms are taken, the bare one-to-one mapping and the parenthesised
"compatible but deprecated" one, which is what xkbcommon's
`xkb_keysym_to_utf32` (src/keysym-utf.c, itself derived from Markus Kuhn's
keysym2ucs.c) maps too. The angle-bracketed form marks keypad and other
duplicates outside this range and is not needed here.

Run:  python3 tools/keysyms/gen-keysym-table.py > palmy/keysym_table.odin
"""
import re
import subprocess
import sys

HEADER = "/usr/include/X11/keysymdef.h"

LINE = re.compile(
    r"^#define XK_(\w+)\s+0x([0-9a-fA-F]+)\s*/\*\s*\(?U\+([0-9A-Fa-f]{4,6}) ([^)*]*?)\)?\s*\*/"
)


def version() -> str:
    try:
        out = subprocess.run(
            ["pacman", "-Q", "xorgproto"], capture_output=True, text=True, check=True
        ).stdout.strip()
        return out
    except Exception:
        return "xorgproto (version unknown)"


def main() -> None:
    table = {}
    for line in open(HEADER, encoding="utf-8"):
        m = LINE.match(line)
        if not m:
            continue
        name, sym, cp, uname = m.group(1), int(m.group(2), 16), int(m.group(3), 16), m.group(4)
        if not (0x0100 <= sym <= 0x20FF):
            continue
        if sym in table:
            continue  # the first name is the canonical one
        table[sym] = (cp, name, uname.strip())

    w = sys.stdout.write
    w("package palmy\n\n")
    w("// GENERATED by tools/keysyms/gen-keysym-table.py from <X11/keysymdef.h>\n")
    w("// (%s). Do not edit; re-run the script.\n" % version())
    w("//\n")
    w("// The legacy keysyms, 0x0100-0x20ff, and the Unicode character each one\n")
    w("// stands for, sorted by keysym for a binary search. Latin-1 and the\n")
    w("// 0x01000000-prefixed Unicode keysyms carry their character in their value\n")
    w("// and are not listed. The same mapping as xkbcommon's xkb_keysym_to_utf32.\n\n")
    w("@(private)\n")
    w("Keysym_Rune :: struct {\n\tsym: u16,\n\tcp:  u16,\n}\n\n")
    w("@(private)\n")
    w("KEYSYM_TABLE := [%d]Keysym_Rune{\n" % len(table))
    for sym in sorted(table):
        cp, name, uname = table[sym]
        if cp > 0xFFFF:
            sys.exit("keysym 0x%04x maps outside the BMP; widen the table" % sym)
        w("\t{0x%04x, 0x%04x}, // %s, %s\n" % (sym, cp, name, uname))
    w("}\n")


if __name__ == "__main__":
    main()
