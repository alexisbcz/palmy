#!/usr/bin/env python3
"""Generate apps/term/vt/key_enum.odin from <ghostty/vt/key/event.h>.

The physical-key numbering has to agree with libghostty's exactly, because the
differential test passes our value straight into their encoder and compares the
bytes. Transcribing 230 names by hand would be one typo away from a test that
says "no differences" while comparing the wrong two keys.

Run:  python3 apps/term/tools/genkeys.py > apps/term/vt/key_enum.odin
"""
import re
import sys

HEADER = "/usr/include/ghostty/vt/key/event.h"


def odinify(name: str) -> str:
    return "_".join(p if p.isdigit() else p.capitalize() for p in name.split("_"))


def main() -> None:
    src = open(HEADER).read()
    m = re.search(r"typedef enum \{([^}]*)\} GhosttyKey;", src, re.S)
    if m is None:
        sys.exit("could not find the GhosttyKey enum in " + HEADER)
    names = re.findall(r"GHOSTTY_KEY_([A-Z0-9_]+)", m.group(1))
    w = sys.stdout.write
    w("package vt\n\n")
    w("// GENERATED by apps/term/tools/genkeys.py from <ghostty/vt/key/event.h>.\n")
    w("//\n")
    w("// These are physical keys in the W3C UI Events `code` sense: layout\n")
    w("// independent, so the key right of Tab is Key.Q on a QWERTY board and on an\n")
    w("// AZERTY board alike, and the letter it produces arrives separately as text.\n")
    w("// The numbering matches libghostty's enum exactly, so the differential test\n")
    w("// can hand our value straight to their encoder.\n\n")
    w("Key :: enum u16 {\n")
    for i, n in enumerate(names):
        w("\t%s = %d,\n" % (odinify(n), i))
    w("}\n\n")
    w("KEY_COUNT :: %d\n" % len(names))


if __name__ == "__main__":
    main()
