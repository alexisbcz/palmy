#!/usr/bin/env python3
"""Generate apps/term/vt/width_table.odin from Python's unicodedata.

The terminal needs one number per codepoint: how many cells it occupies.
The rules below are the ones every terminal converges on, written out so the
table can be regenerated when Python's Unicode version moves:

  0  combining marks (Mn, Me), Hangul Jamo medial/final, the format
     characters that are not meant to occupy a cell, and the unassigned
     Default_Ignorable blocks
  2  East Asian Wide and Fullwidth, plus the regional indicators, which are
     neutral in the East Asian width table but always drawn as a flag pair
  1  everything else, including C0/C1 controls (a terminal never asks for the
     width of a control; answering 1 matches libghostty)

Run:  python3 apps/term/tools/genwidth.py > apps/term/vt/width_table.odin
"""
import sys
import unicodedata

MAX = 0x110000

# Format characters that take a cell rather than disappearing: the soft hyphen,
# the Arabic subtending marks (which prefix and enclose the following digits)
# and the Arabic letter mark.
CF_VISIBLE = {0x00AD, 0x061C, 0x06DD, 0x08E2} | set(range(0x0600, 0x0606))

# Unassigned ranges with Default_Ignorable_Code_Point=Yes.
DI_UNASSIGNED = [
    (0x2065, 0x2065),
    (0xFFF0, 0xFFF8),
    (0xE0000, 0xE0000),
    (0xE0002, 0xE001F),
    (0xE0080, 0xE00FF),
    (0xE01F0, 0xE0FFF),
]

REGIONAL_INDICATORS = (0x1F1E6, 0x1F1FF)


def width(cp: int) -> int:
    ch = chr(cp)
    cat = unicodedata.category(ch)
    if cat in ("Mn", "Me"):
        return 0
    if cat == "Cf" and cp not in CF_VISIBLE:
        return 0
    if 0x1160 <= cp <= 0x11FF:  # Hangul Jamo medial vowels and final consonants
        return 0
    for lo, hi in DI_UNASSIGNED:
        if lo <= cp <= hi:
            return 0
    if REGIONAL_INDICATORS[0] <= cp <= REGIONAL_INDICATORS[1]:
        return 2
    if unicodedata.east_asian_width(ch) in ("W", "F"):
        return 2
    return 1


def main() -> None:
    w = [width(cp) for cp in range(MAX)]
    runs = []
    cp = 0
    while cp < MAX:
        v = w[cp]
        if v == 1:
            cp += 1
            continue
        j = cp
        while j + 1 < MAX and w[j + 1] == v:
            j += 1
        runs.append((cp, j, v))
        cp = j + 1

    out = [
        "package vt\n",
        "\n",
        "// GENERATED by apps/term/tools/genwidth.py from Unicode %s.\n"
        % unicodedata.unidata_version,
        "// Do not edit by hand. Each row is {lo, hi, width} and covers every\n",
        "// codepoint whose width is not 1; anything not listed is one cell.\n",
        "\n",
        "WIDTH_RUNS := [%d][3]i32{\n" % len(runs),
    ]
    for lo, hi, v in runs:
        out.append("\t{0x%05X, 0x%05X, %d},\n" % (lo, hi, v))
    out.append("}\n")
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
