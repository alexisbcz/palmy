#!/usr/bin/env bash
# web-build.sh: build a palmy application for the browser.
#
#   apps/tools/web-build.sh <app-dir> <out-dir> [options]
#
#   --ship <file>        put a file (a font, usually) in the page's filesystem
#                        at the same absolute path; repeatable
#   --ship-list <file>   one path per line, as --ship
#   --args "<a> <b>"     the program's argv after its name (default: none)
#   --env "K=V K2=V2"    its environment (the page's ?env= adds to it)
#   --title <t>          the page title (default: the app directory's name)
#   --debug              -debug instead of -o:speed
#
# The output directory is a static site: index.html, palmy-web.js, app.wasm,
# manifest.json and files/. Serve it with anything (palmy/web/serve.mjs does,
# with the right MIME type for .wasm) and open it in Chromium 137 or later.
#
# How it builds without touching the native tree: palmy/ is one Odin package,
# and seven of its files speak Wayland, X11 or Linux syscalls. The package is
# staged into <out-dir>/.stage with those seven left out and palmy/web/odin/
# put in their place, and the neutral parts of window.odin and xkb.odin (the
# input types, the toplevel wrappers, the KEY_ constants and keysym helpers)
# are lifted out of the originals verbatim so they have one source. apps/kit is
# staged the same way, minus notify.odin (a Unix socket to the notification
# daemon; an app that sends notifications does not build for the web yet).
# Nothing under palmy/ or apps/ is modified, and a native build never
# sees palmy/web/odin: it is a subdirectory, and its files are #+build wasi.
#
# Runs in the build VM (it needs Odin and wasm-ld).
set -euo pipefail

usage() {
	sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
	exit 2
}

[ $# -ge 2 ] || usage
APP=$(cd "$1" && pwd)
OUT=$2
shift 2

SHIP=()
ARGS=""
ENVS=""
TITLE=$(basename "$APP")
OPT=(-o:speed)
while [ $# -gt 0 ]; do
	case $1 in
	--ship) SHIP+=("$2"); shift 2 ;;
	--ship-list)
		while IFS= read -r l; do [ -n "$l" ] && SHIP+=("$l"); done <"$2"
		shift 2 ;;
	--args) ARGS=$2; shift 2 ;;
	--env) ENVS=$2; shift 2 ;;
	--title) TITLE=$2; shift 2 ;;
	--debug) OPT=(-debug); shift ;;
	*) echo "web-build: unknown option $1" >&2; usage ;;
	esac
done

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
# Every engine that has JSPI has these; the frame is byte-identical with and
# without them (palmy/web/README.md) and about a quarter faster with.
# WEB_FEATURES= (empty) builds plain wasm32.
WEB_FEATURES=${WEB_FEATURES-bulk-memory,simd128,nontrapping-fptoint,sign-ext}
ODIN=${ODIN:-$HOME/.local/share/mise/installs/odin/dev-2026-09/odin}
for d in /usr/lib/llvm-18/bin /usr/lib/llvm/bin; do
	[ -x "$d/wasm-ld" ] && PATH=$d:$PATH
done
command -v wasm-ld >/dev/null || { echo "web-build: wasm-ld not found (apt install lld)" >&2; exit 1; }

mkdir -p "$OUT"
OUT=$(cd "$OUT" && pwd)
STAGE=$OUT/.stage
rm -rf "$STAGE"
mkdir -p "$STAGE/palmy" "$STAGE/kit"

# --- palmy -----------------------------------------------------------------
NATIVE_ONLY="window.odin wayland.odin x11.odin xauth.odin wire.odin xkb.odin clipboard.odin"
for f in "$ROOT"/palmy/*.odin; do
	b=$(basename "$f")
	case " $NATIVE_ONLY " in *" $b "*) continue ;; esac
	cp "$f" "$STAGE/palmy/"
done
cp "$ROOT"/palmy/web/odin/*.odin "$STAGE/palmy/"

# lift copies the lines of $1 from the first matching /$2/ up to, not
# including, the first later line matching /$3/ (or to the end when $3 is
# empty), and fails if the start marker is gone: an edit to the original that
# moved it should stop this build, not silently drop half a file.
lift() {
	local src=$1 from=$2 to=$3 out
	out=$(awk -v from="$from" -v to="$to" '
		!on && $0 ~ from { on = 1 }
		on && to != "" && seen && $0 ~ to { exit }
		on { print; seen = 1 }
	' "$src")
	if [ -z "$out" ]; then
		echo "web-build: marker /$from/ not found in $src; update apps/tools/web-build.sh" >&2
		exit 1
	fi
	printf '%s\n' "$out"
}

{
	echo '#+build wasi'
	echo 'package palmy'
	echo
	echo '// GENERATED by apps/tools/web-build.sh from palmy/window.odin: the'
	echo '// backend-neutral types and the toplevel wrappers. Do not edit.'
	echo
	echo 'import "core:strings"'
	echo
	lift "$ROOT/palmy/window.odin" '^// Layer picks' '^Window :: struct'
	lift "$ROOT/palmy/window.odin" '^// App-level wrappers' ''
} >"$STAGE/palmy/window_shared_wasi.odin"

{
	echo '#+build wasi'
	echo 'package palmy'
	echo
	echo '// GENERATED by apps/tools/web-build.sh from palmy/xkb.odin: the keysym'
	echo '// constants and helpers, without the libxkbcommon half. Do not edit.'
	echo
	lift "$ROOT/palmy/xkb.odin" '^// Keysyms, matching' '^@\(private\)$'
	# The helpers start at the @(private) above keysym_upper.
	awk '/^keysym_upper :: proc/ { found = 1 } { lines[NR] = $0 } END {
		if (!found) exit 1
		for (i = 1; i <= NR; i++) if (lines[i] ~ /^keysym_upper :: proc/) { start = i - 1; break }
		for (i = start; i <= NR; i++) print lines[i]
	}' "$ROOT/palmy/xkb.odin" || { echo "web-build: keysym_upper not found in xkb.odin" >&2; exit 1; }
} >"$STAGE/palmy/keysyms_wasi.odin"

# --- kit -------------------------------------------------------------------
for f in "$ROOT"/apps/kit/*.odin; do
	b=$(basename "$f")
	[ "$b" = notify.odin ] && continue
	cp "$f" "$STAGE/kit/"
done

# --- compile ---------------------------------------------------------------
# Two gaps in the Odin toolchain's WebAssembly support are bridged by building
# against an overlay of the Odin root: symlinks to the real one, except for
# the files below. Nothing in the Odin install is changed.
#
#  - core:os reads a WASI directory with an inverted assert (dir_wasi.odin:
#    `assert(len(buf) < int(entry.d_namlen))`), so the first directory
#    listing -- palmy's font scan -- traps. The overlay turns it round.
#  - vendor:stb/image has no stdio on wasm, so `stbi.write_png`, which
#    palmy's offscreen_write_png and image.odin call, does not exist there.
#    The overlay adds it, over `write_png_to_func` and core:os, which on WASI
#    is the page's filesystem (palmy/web/odin-root/).
#  - core:mem/virtual has no wasm implementation (its reservation is a nil
#    block), and palmy's per-frame arenas are virtual.Arena. The overlay adds
#    one over the wasm heap.
#  - vendor:libc-shim implements powf, cosf, sinf, pow, cos, sin and exp with
#    core:math, whose versions of them lower to calls to those same symbols on
#    wasm: infinite recursion on the first math.pow. The overlay points them
#    at the browser's Math (the palmy_libm imports) and adds expf.
ODIN_REAL=$(readlink -f "$ODIN")
ODIN_HOME=$(dirname "$ODIN_REAL")
FIXED=$OUT/.odin-root
rm -rf "$FIXED"
# unfold <dir relative to the root>: replace a symlinked directory in the
# overlay with a real one whose entries are symlinks, so one file in it can
# be swapped.
unfold() {
	local rel=$1 cur=$FIXED part
	IFS=/ read -ra parts <<<"$rel"
	for part in "${parts[@]}"; do
		cur=$cur/$part
		if [ -L "$cur" ]; then
			local real
			real=$(readlink "$cur")
			rm "$cur"
			mkdir "$cur"
			for e in "$real"/*; do ln -s "$e" "$cur/$(basename "$e")"; done
		fi
	done
}
mkdir -p "$FIXED"
for e in "$ODIN_HOME"/*; do ln -s "$e" "$FIXED/$(basename "$e")"; done
unfold core/os
if grep -q 'assert(len(buf) < int(entry.d_namlen))' "$ODIN_HOME/core/os/dir_wasi.odin"; then
	rm "$FIXED/core/os/dir_wasi.odin"
	sed 's/assert(len(buf) < int(entry.d_namlen))/assert(len(buf) >= int(entry.d_namlen))/' \
		"$ODIN_HOME/core/os/dir_wasi.odin" >"$FIXED/core/os/dir_wasi.odin"
fi
unfold vendor/stb/image
cp "$ROOT"/palmy/web/odin-root/vendor/stb/image/*.odin "$FIXED/vendor/stb/image/"
unfold core/mem/virtual
rm "$FIXED/core/mem/virtual/virtual_other.odin"
{
	echo '#+build !wasi'
	cat "$ODIN_HOME/core/mem/virtual/virtual_other.odin"
} >"$FIXED/core/mem/virtual/virtual_other.odin"
cp "$ROOT"/palmy/web/odin-root/core/mem/virtual/*.odin "$FIXED/core/mem/virtual/"
unfold vendor/libc-shim
rm "$FIXED/vendor/libc-shim/math.odin"
awk '
	/link_name="/ { match($0, /link_name="[^"]*"/); name = substr($0, RSTART + 11, RLENGTH - 12) }
	/^\treturn math\.(sin|cos|pow|exp)\(/ {
		f = $0; sub(/^\treturn math\./, "", f); sub(/\(.*/, "", f)
		args = $0; sub(/^[^(]*\(/, "", args); sub(/\)$/, "", args)
		if (name ~ /f$/) {
			n = split(args, a, /, */); call = ""
			for (i = 1; i <= n; i++) call = call (i > 1 ? ", " : "") "f64(" a[i] ")"
			print "\treturn f32(libm_" f "(" call "))"
		} else print "\treturn libm_" f "(" args ")"
		next
	}
	{ print }
' "$ODIN_HOME/vendor/libc-shim/math.odin" >"$FIXED/vendor/libc-shim/math.odin"
if grep -qE 'return math\.(sin|cos|pow|exp)\(' "$FIXED/vendor/libc-shim/math.odin"; then
	echo "web-build: could not rewrite libc-shim/math.odin" >&2
	exit 1
fi
cp "$ROOT"/palmy/web/odin-root/vendor/libc-shim/*.odin "$FIXED/vendor/libc-shim/"
export ODIN_ROOT=$FIXED

"$ODIN" build "$APP" -target:wasi_wasm32 "${OPT[@]}" ${WEB_FEATURES:+-target-features:"$WEB_FEATURES"} \
	-collection:palmy="$STAGE/palmy" \
	-collection:shadcn="$ROOT/shadcn" \
	-collection:kit="$STAGE/kit" \
	-extra-linker-flags:"--max-memory=4294967296 -z stack-size=8388608" \
	-out:"$OUT/app.wasm"

# --- the page --------------------------------------------------------------
cp "$ROOT/palmy/web/js/palmy-web.js" "$OUT/"
sed "s|@TITLE@|$TITLE|g" "$ROOT/palmy/web/js/index.html" >"$OUT/index.html"

rm -rf "$OUT/files"
mkdir -p "$OUT/files"
{
	printf '{\n  "args": ['
	sep=""
	for a in $TITLE $ARGS; do printf '%s"%s"' "$sep" "$a"; sep=", "; done
	printf '],\n  "env": ['
	sep=""
	for e in $ENVS; do printf '%s"%s"' "$sep" "$e"; sep=", "; done
	printf '],\n  "files": ['
	sep=""
	i=0
	for f in "${SHIP[@]+"${SHIP[@]}"}"; do
		if [ ! -f "$f" ]; then
			echo "web-build: --ship $f: no such file" >&2
			exit 1
		fi
		i=$((i + 1))
		name=$(printf '%03d-%s' "$i" "$(basename "$f")")
		cp -L "$f" "$OUT/files/$name"
		printf '%s\n    {"path": "%s", "url": "files/%s"}' "$sep" "$f" "$name"
		sep=","
	done
	printf '\n  ]\n}\n'
} >"$OUT/manifest.json"

echo "web-build: $OUT/app.wasm ($(du -h "$OUT/app.wasm" | cut -f1)), ${#SHIP[@]} shipped files"
